/// Centralized constants for all application route paths and names.
abstract class AppRoutes {
  /// Default search and song discovery tab.
  static const String search = '/search';

  /// User's saved moments tab.
  static const String moments = '/moments';

  /// Moment collections / groups tab.
  static const String groups = '/groups';

  /// User profile and library stats tab.
  static const String profile = '/profile';

  /// Expanded full player route (top-level modal screen).
  static const String player = '/player';
}
